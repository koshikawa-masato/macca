// server/sjis.go の Shift_JIS デコードテーブルを生成する。
// Node.js の TextDecoder('shift_jis') (WHATWG encoding / ICU) を正として、
// 全バイト列の復号結果を Go のテーブルに落とす。
//
//   使い方: node build/gen-sjis/gen.mjs > server/sjis.go
//
// 生成物はコミット済みなので、通常は再実行不要。

function tryDecode(bytes) {
  try {
    return new TextDecoder('shift_jis', { fatal: true }).decode(Uint8Array.from(bytes));
  } catch {
    return null;
  }
}

// 1 バイト文字 (ASCII / 半角カナ)
const singles = [];
for (let b = 0; b <= 0xff; b++) {
  const s = tryDecode([b]);
  if (s !== null && s.length === 1) singles.push([b, s.codePointAt(0)]);
}

// 2 バイト文字
const doubles = [];
for (let hi = 0x81; hi <= 0xfc; hi++) {
  if (hi > 0x9f && hi < 0xe0) continue; // リード範囲外
  for (let lo = 0x40; lo <= 0xfc; lo++) {
    if (lo === 0x7f) continue;
    const s = tryDecode([hi, lo]);
    if (s !== null && s.length === 1) doubles.push([(hi << 8) | lo, s.codePointAt(0)]);
  }
}

const out = [];
out.push('// Code generated by build/gen-sjis/gen.mjs; DO NOT EDIT.');
out.push('// Shift_JIS (CP932) デコードテーブル。Node の TextDecoder(\'shift_jis\') と同一の結果を返す。');
out.push('');
out.push('package main');
out.push('');
out.push('var sjisSingle = map[byte]rune{');
out.push(singles.map(([b, cp]) => `0x${b.toString(16).padStart(2, '0')}: 0x${cp.toString(16)}`).join(', ') + ',');
out.push('}');
out.push('');
out.push('var sjisDouble = map[uint16]rune{');
for (let i = 0; i < doubles.length; i += 8) {
  out.push('\t' + doubles.slice(i, i + 8)
    .map(([k, cp]) => `0x${k.toString(16).padStart(4, '0')}: 0x${cp.toString(16)}`)
    .join(', ') + ',');
}
out.push('}');
out.push('');
console.log(out.join('\n'));
